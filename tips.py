# ===== Helpers =====

def send_photo_to_telegram(image_url, caption):
    url = f"https://api.telegram.org/bot{TELEGRAM_BOT_TOKEN}/sendPhoto"
    payload = {
        "chat_id": TELEGRAM_CHANNEL_ID,
        "photo":   image_url,
        "caption": caption,
        "parse_mode": "HTML",
    }
    for attempt in range(3):
        try:
            r = requests.post(url, data=payload, timeout=15)
            if r.status_code == 200:
                return True
            print(f"Telegram error ({r.status_code}):", r.text)
        except Exception as e:
            print(f"Attempt {attempt+1} failed:", e)
        time.sleep(2)
    return False

def send_message_to_telegram(message):
    """Fallback if image fails"""
    url = f"https://api.telegram.org/bot{TELEGRAM_BOT_TOKEN}/sendMessage"
    payload = {
        "chat_id": TELEGRAM_CHANNEL_ID,
        "text":    message,
        "parse_mode": "HTML",
        "disable_web_page_preview": True,
    }
    r = requests.post(url, data=payload, timeout=10)
    return r.status_code == 200

def main():
    now = datetime.now(timezone.utc)
    print(f"📚 Tips bot started — {now.strftime('%Y-%m-%d %H:%M UTC')}")

    # Pick today's tip based on day of year
    tip_index = now.timetuple().tm_yday % len(TIPS)
    image_index = now.timetuple().tm_yday % len(IMAGES)

    tip   = TIPS[tip_index]
    image = IMAGES[image_index]

    caption = (
        f"📚 <b>نکته تکنیکال روز</b>\n\n"
        f"🎯 <b>{tip['title']}</b>\n\n"
        f"{tip['body']}\n\n"
        f"━━━━━━━━━━━━━━━\n"
        f"👥 @Crypto_Zone360\n"
        f"به ما بپیوندید 🦈\n\n"
        f"#تحلیل_تکنیکال #آموزش_کریپتو #کریپتو #ارز_دیجیتال"
    )

    # Truncate caption to 1024 chars (Telegram limit for photo captions)
    if len(caption) > 1024:
        caption = caption[:1020] + "…"

    success = send_photo_to_telegram(image, caption)

    if not success:
        print("Photo failed, trying text only...")
        success = send_message_to_telegram(caption)

    if success:
        print(f"✅ Tip posted: {tip['title']}")
    else:
        print("❌ Failed to post tip.")

if __name__ == "__main__":
    main()
